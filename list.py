# 2. Replace all spaces with underscores
s = "Python is fun and powerful"
print(s.replace(" ", "_"))
# 3. Check if the string contains only digits
s = "12345"
print(s.isdigit())
# 4. Print the string in reverse order
s = "Python is amazing"
print(s[::-1])
